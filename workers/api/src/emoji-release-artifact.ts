export interface ReleaseRecord {
  id: string; emoji: string; short_name: string; keywords: string[];
  category: string | null; subcategory: string | null; codepoints: string[]; sort_order: number | null;
}
export interface ReleaseManifest {
  schemaVersion: number; recordsSHA256: string; moduleSHA256: string;
  identitySHA256: string; entryCount: number; version: string;
}
export interface VerifiedEmojiArtifact { version: string; records: ReleaseRecord[]; manifest: ReleaseManifest }
const HASH = /^[a-f0-9]{64}$/u;
const UUID = /^[a-f0-9]{8}-(?:[a-f0-9]{4}-){3}[a-f0-9]{12}$/u;
function fail(): never { throw new Error("release_artifact_invalid"); }
export function canonicalReleaseValue(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonicalReleaseValue).join(",")}]`;
  if (value !== null && typeof value === "object") return `{${Object.keys(value).sort().map(key =>
    `${JSON.stringify(key)}:${canonicalReleaseValue((value as Record<string, unknown>)[key])}`).join(",")}}`;
  const json = JSON.stringify(value); if (json === undefined) fail(); return json;
}
async function digest(value: string): Promise<string> {
  return [...new Uint8Array(await crypto.subtle.digest("SHA-256", new TextEncoder().encode(value)))]
    .map(byte => byte.toString(16).padStart(2,"0")).join("");
}
function object(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}
function keys(value: Record<string, unknown>, expected: string[]): void {
  if (canonicalReleaseValue(Object.keys(value).sort()) !== canonicalReleaseValue(expected.sort())) fail();
}
function strings(value: unknown): value is string[] {
  return Array.isArray(value) && value.length <= 200 && value.every(x => typeof x === "string" && x.length <= 1024);
}
function normalize(emoji: string): string { return emoji.normalize("NFC").replace(/\uFE0F+/gu,"\uFE0F"); }
export function validateReleaseRecords(value: unknown): asserts value is ReleaseRecord[] {
  if (!Array.isArray(value) || value.length < 1 || value.length > 20_000) fail();
  const ids = new Set<string>(), emojis = new Set<string>();
  for (const r of value) {
    if (!object(r)) fail();
    keys(r,["id","emoji","short_name","keywords","category","subcategory","codepoints","sort_order"]);
    if (typeof r.id !== "string" || !UUID.test(r.id) || typeof r.emoji !== "string" || !r.emoji || r.emoji.length > 128 ||
        typeof r.short_name !== "string" || r.short_name.length > 1024 || !strings(r.keywords) || !strings(r.codepoints) ||
        r.codepoints.length < 1 || r.codepoints.length > 64 || r.codepoints.some(x => !/^[A-F0-9]{4,6}$/u.test(x)) ||
        !(r.category === null || typeof r.category === "string") || !(r.subcategory === null || typeof r.subcategory === "string") ||
        !(r.sort_order === null || Number.isSafeInteger(r.sort_order))) fail();
    if (Object.hasOwn(Object.prototype,normalize(r.emoji)) ||
        (typeof r.category === "string" && (r.category.length>1024 || Object.hasOwn(Object.prototype,r.category))) ||
        (typeof r.subcategory === "string" && r.subcategory.length>1024)) fail();
    const actual = [...r.emoji].map(c => c.codePointAt(0)!.toString(16).toUpperCase().padStart(4,"0"));
    if (canonicalReleaseValue(actual) !== canonicalReleaseValue(r.codepoints) || ids.has(r.id) || emojis.has(normalize(r.emoji))) fail();
    ids.add(r.id); emojis.add(normalize(r.emoji));
  }
}
/** Verifies stored immutable rows independently of the producer's ICU collation. */
export async function rebuildStoredEmojiRelease(records: unknown, manifest: unknown): Promise<VerifiedEmojiArtifact> {
  validateReleaseRecords(records); if (!object(manifest)) fail();
  keys(manifest,["schemaVersion","recordsSHA256","moduleSHA256","identitySHA256","entryCount","version"]);
  if (manifest.schemaVersion !== 1 || manifest.entryCount !== records.length ||
      [manifest.recordsSHA256,manifest.moduleSHA256,manifest.identitySHA256,manifest.version].some(x => typeof x !== "string" || !HASH.test(x))) fail();
  const sorted = [...records].sort((a,b)=>a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
  const source = canonicalReleaseValue(sorted)+"\n";
  if (await digest(source) !== manifest.recordsSHA256 || await digest(canonicalReleaseValue(sorted.map(({id,emoji,codepoints})=>
      ({id,emoji,codepoints})))) !== manifest.identitySHA256) fail();
  const {version,...body} = manifest;
  if (await digest(canonicalReleaseValue(body)) !== version) fail();
  return {version: version as string,records:sorted,manifest:manifest as unknown as ReleaseManifest};
}
function verifyModule(module: string, records: ReleaseRecord[]): void {
  const header = "// Auto-generated by scripts/generate-emoji-catalog.ts\n// Do not edit this file directly.\n\nexport const emojiCatalogEntries = ";
  if (!module.startsWith(header)) fail(); let rest = module.slice(header.length);
  const take = (delimiter: string): unknown => { const end = rest.indexOf(delimiter); if (end < 0) fail();
    let parsed: unknown; try { parsed=JSON.parse(rest.slice(0,end)); } catch { fail(); }
    rest=rest.slice(end+delimiter.length); return parsed; };
  const entries = take(" as const;\nexport const emojiIdToEmoji: Record<string, string> = ");
  const idToEmoji = take(";\nexport const emojiToId: Record<string, string> = ");
  const emojiToId = take(";\nexport const emojiCategories: Record<string, string[]> = ");
  const categories = take(";\n\nexport default {\n  entries: emojiCatalogEntries,\n  idToEmoji: emojiIdToEmoji,\n  emojiToId,\n  categories: emojiCategories,\n};\n");
  if (rest || !Array.isArray(entries) || entries.length !== records.length || !object(categories)) fail();
  const byId=new Map(records.map(r=>[r.id,r])); const seen=new Set<string>(); let previousOrder=-Infinity;
  const groups=new Map<string,string[]>();const expectedEntries:unknown[]=[];
  for (const e of entries) {
    if (!object(e) || typeof e.id !== "string") fail();const r=byId.get(e.id);if (!r || seen.has(r.id)) fail();seen.add(r.id);
    const expectedEntry={id:r.id,emoji:r.emoji,shortName:r.short_name,keywords:r.keywords,
      category:r.category,subcategory:r.subcategory,codepoints:r.codepoints};
    if (canonicalReleaseValue(e) !== canonicalReleaseValue(expectedEntry)) fail();expectedEntries.push(expectedEntry);
    const order=r.sort_order ?? Number.MAX_SAFE_INTEGER;if (order < previousOrder) fail();previousOrder=order;
    if (r.category) groups.set(r.category,[...(groups.get(r.category) ?? []),r.id]);
  }
  if (canonicalReleaseValue(idToEmoji) !== canonicalReleaseValue(Object.fromEntries(records.map(r=>[r.id,r.emoji]))) ||
      canonicalReleaseValue(emojiToId) !== canonicalReleaseValue(Object.fromEntries(records.map(r=>[normalize(r.emoji),r.id]))) ||
      canonicalReleaseValue(Object.keys(categories).sort()) !== canonicalReleaseValue([...groups.keys()].sort())) fail();
  for (const [category,ids] of groups) {
    const actual=categories[category];if (!Array.isArray(actual) || actual.some(x=>typeof x !== "string") ||
      canonicalReleaseValue([...actual].sort()) !== canonicalReleaseValue([...ids].sort())) fail();
  }
  // Preserve the producer's verified tie/category order, but require its exact
  // JSON-only formatter. Re-sorting here would depend on the Worker's ICU version.
  const orderedRecords=entries.map(e=>byId.get((e as {id:string}).id)!);
  const rendered=header+JSON.stringify(expectedEntries,null,2)+" as const;\nexport const emojiIdToEmoji: Record<string, string> = "+
    JSON.stringify(Object.fromEntries(orderedRecords.map(r=>[r.id,r.emoji])),null,2)+";\nexport const emojiToId: Record<string, string> = "+
    JSON.stringify(Object.fromEntries(orderedRecords.map(r=>[normalize(r.emoji),r.id])),null,2)+";\nexport const emojiCategories: Record<string, string[]> = "+
    JSON.stringify(Object.fromEntries([...groups.keys()].map(category=>[category,categories[category]])),null,2)+
    ";\n\nexport default {\n  entries: emojiCatalogEntries,\n  idToEmoji: emojiIdToEmoji,\n  emojiToId,\n  categories: emojiCategories,\n};\n";
  if(rendered!==module)fail();
}
/** Never evaluates supplied JavaScript: only the fixed generated JSON module grammar is accepted. */
export async function verifyEmojiReleasePayload(input: unknown): Promise<VerifiedEmojiArtifact> {
  if (!object(input)) fail(); keys(input,["recordsSource","moduleSource","manifest"]);
  if (typeof input.recordsSource !== "string" || typeof input.moduleSource !== "string" ||
      input.recordsSource.length > 8_000_000 || input.moduleSource.length > 8_000_000) fail();
  let records: unknown; try { records=JSON.parse(input.recordsSource); } catch { fail(); }
  const verified=await rebuildStoredEmojiRelease(records,input.manifest);
  if (canonicalReleaseValue(verified.records)+"\n" !== input.recordsSource ||
      await digest(input.moduleSource) !== verified.manifest.moduleSHA256) fail();
  verifyModule(input.moduleSource,verified.records);return verified;
}
