#!/usr/bin/env node

/**
 * Build a catalog-driven PostgreSQL row projection and convert its strict JSON
 * envelope into ordered D1 bindings. This module never connects to PostgreSQL,
 * reads source rows, or applies a migration.
 */

import { randomBytes } from "node:crypto";
import { promises as fs } from "node:fs";
import path from "node:path";
import process from "node:process";
import { pathToFileURL } from "node:url";

import { convertPgText } from "./value-conversion.mjs";
import { convertSchema } from "./schema-convert.mjs";

export const ROW_ENVELOPE_VERSION = 1;

const IDENTIFIER_RE = /^[A-Za-z_][A-Za-z0-9_]*$/;
const SUPPORTED_CODECS = new Set([
  "text",
  "uuid-text",
  "boolean-int01",
  "smallint-int16",
  "integer-int32",
  "bigint-int64-exact",
  "date-ymd-text",
  "timestamptz-utc-microsecond-text",
  "json-text",
  "postgres-array-json-text",
  "money-cents-int64",
  "decimal-canonical-text",
  "enum-text-check",
  "credential-to-bcrypt",
]);
const ARRAY_TYPES = new Set(["text[]", "uuid[]", "smallint[]"]);
const SEQUENCE_UUID_ARRAY_TABLES = new Set([
  "fanmark_discoveries",
  "fanmark_events",
  "fanmark_favorites",
  "fanmarks",
]);
const UUID_TEXT_RE = /^[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}$/iu;
const EXACT_ENVELOPE_KEYS = ["schemaVersion", "table", "columns", "values", "arrayMetadata"];
const EXACT_ARRAY_METADATA_KEYS = ["isNull", "ndims", "lowerBound"];

export class RowConversionError extends Error {
  constructor(code, cause) {
    super(code);
    this.name = "RowConversionError";
    this.code = code;
    if (cause !== undefined) this.cause = cause;
  }
}

function fail(code, cause) {
  return new RowConversionError(code, cause);
}

function isPlainObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function quoteIdentifier(value) {
  return `"${String(value).replaceAll('"', '""')}"`;
}

function quoteLiteral(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function assertExactKeys(value, expected, code) {
  if (!isPlainObject(value)) throw fail(code);
  const actual = Object.keys(value).sort();
  const wanted = [...expected].sort();
  if (actual.length !== wanted.length || actual.some((key, index) => key !== wanted[index])) throw fail(code);
}

function compareColumns(left, right) {
  return left.ordinal - right.ordinal || left.column_name.localeCompare(right.column_name);
}

const DATE_LOWER_BOUND = "DATE '0001-01-01'";
const DATE_UPPER_BOUND = "DATE '10000-01-01'";
const TIMESTAMPTZ_LOWER_BOUND = "TIMESTAMPTZ '0001-01-01 00:00:00+00'";
const TIMESTAMPTZ_UPPER_BOUND = "TIMESTAMPTZ '10000-01-01 00:00:00+00'";

function sourceProjection(column) {
  const name = quoteIdentifier(column.column_name);
  if (column.postgres_type === "timestamp with time zone") {
    return `(CASE
    WHEN ${name} IS NULL THEN NULL
    WHEN ${name} >= ${TIMESTAMPTZ_LOWER_BOUND} AND ${name} < ${TIMESTAMPTZ_UPPER_BOUND}
      THEN to_char(${name} AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"')
    ELSE ${name}::text
  END)`;
  }
  if (column.postgres_type === "date") {
    return `(CASE
    WHEN ${name} IS NULL THEN NULL
    WHEN ${name} >= ${DATE_LOWER_BOUND} AND ${name} < ${DATE_UPPER_BOUND}
      THEN to_char(${name}, 'YYYY-MM-DD')
    ELSE ${name}::text
  END)`;
  }
  if (ARRAY_TYPES.has(column.postgres_type)) return `array_to_json(${name})::text`;
  return `${name}::text`;
}

function arrayMetadataProjection(column) {
  const name = quoteIdentifier(column.column_name);
  return [
    quoteLiteral(column.column_name),
    `jsonb_build_object(
      'isNull', ${name} IS NULL,
      'ndims', CASE WHEN ${name} IS NULL THEN NULL ELSE COALESCE(array_ndims(${name}), 0) END,
      'lowerBound', CASE WHEN ${name} IS NULL THEN NULL ELSE array_lower(${name}, 1) END
    )`,
  ];
}

function valuesProjection(columns) {
  return columns
    .map((column) => `      (${quoteLiteral(column.column_name)}, ${sourceProjection(column)})`)
    .join(",\n");
}

function arrayMetadataValuesProjection(columns) {
  return columns
    .map((column) => {
      const [key, value] = arrayMetadataProjection(column);
      return `      (${key}, ${value})`;
    })
    .join(",\n");
}

function buildSelectSql(tableName, columns, schemaName) {
  const arrayColumns = columns.filter((column) => ARRAY_TYPES.has(column.postgres_type));
  const metadata = arrayColumns.length === 0
    ? "'{}'::jsonb"
    : `COALESCE((
    SELECT jsonb_object_agg(array_values.column_name, array_values.metadata)
    FROM (VALUES
${arrayMetadataValuesProjection(arrayColumns)}
    ) AS array_values(column_name, metadata)
  ), '{}'::jsonb)`;
  return [
    "-- Generated by scripts/migration/row-conversion.mjs.",
    "-- Catalog-only projection; execute only in a reviewed, consistent source snapshot.",
    `-- Envelope columns: ${columns.length}; array metadata columns: ${arrayColumns.length}.`,
    "SELECT jsonb_build_object(",
    `  'schemaVersion', ${ROW_ENVELOPE_VERSION},`,
    `  'table', ${quoteLiteral(tableName)},`,
    `  'columns', ARRAY[${columns.map((column) => quoteLiteral(column.column_name)).join(", ")}]::text[],`,
    "  'values', (",
    "    SELECT jsonb_object_agg(row_values.column_name, row_values.column_text)",
    "    FROM (VALUES",
    valuesProjection(columns),
    "    ) AS row_values(column_name, column_text)",
    "  ),",
    `  'arrayMetadata', ${metadata}`,
    `)::text AS ${quoteIdentifier("__fanmark_row_envelope")}`,
    `FROM ${quoteIdentifier(schemaName)}.${quoteIdentifier(tableName)};`,
    "",
  ].join("\n");
}

function buildEnumLabels(catalog) {
  const labels = new Map();
  for (const entry of catalog.enums) {
    const values = labels.get(entry.type_name) ?? new Set();
    values.add(entry.value);
    labels.set(entry.type_name, values);
  }
  return labels;
}

function codecConverterType(column, codec) {
  const sourceType = column.postgres_type.toLowerCase();
  const expected = new Map([
    ["text", new Set(["text"])],
    ["uuid-text", new Set(["uuid"])],
    ["boolean-int01", new Set(["boolean"])],
    ["smallint-int16", new Set(["smallint"])],
    ["integer-int32", new Set(["integer"])],
    ["bigint-int64-exact", new Set(["bigint"])],
    ["date-ymd-text", new Set(["date"])],
    ["timestamptz-utc-microsecond-text", new Set(["timestamp with time zone"])],
    ["json-text", new Set(["jsonb"])],
    ["postgres-array-json-text", ARRAY_TYPES],
    // numeric(10,2) is accepted only where schema-convert explicitly marked
    // it as a reviewed cents column. Other fixed-scale decimals stay gated.
    ["money-cents-int64", new Set(["numeric(10,2)"])],
    ["decimal-canonical-text", new Set(["numeric"])],
    // Snapshot export still validates the source value as text. The codec
    // names the required future D1 transform; it does not hash or authorize a
    // generic D1 binding.
    ["credential-to-bcrypt", new Set(["text"])],
  ]);
  if (codec === "enum-text-check") {
    return column.type_kind === "e" ? "text" : null;
  }
  return expected.get(codec)?.has(sourceType) ? sourceType : null;
}

function createPlan(catalogInput, tableName, options = {}) {
  if (!isPlainObject(catalogInput)) throw fail("invalid_catalog");
  if (typeof tableName !== "string" || !IDENTIFIER_RE.test(tableName)) throw fail("unsafe_table_name");
  const schemaName = options.schema ?? "public";
  if (typeof schemaName !== "string" || !IDENTIFIER_RE.test(schemaName)) throw fail("unsafe_schema_name");

  let structural;
  try {
    structural = convertSchema(
      catalogInput,
      options.credentialDescriptor === undefined ? {} : { credentialDescriptor: options.credentialDescriptor },
    );
  } catch (error) {
    throw fail("invalid_catalog", error);
  }
  if (!Array.isArray(catalogInput.columns) || !Array.isArray(catalogInput.enums)) throw fail("invalid_catalog");
  const columns = catalogInput.columns.filter((column) => column.table_name === tableName).sort(compareColumns);
  if (columns.length === 0) throw fail("unknown_table");

  const codecs = new Map(structural.report.target.columnCodecs.map((entry) => [`${entry.table}\0${entry.column}`, entry]));
  const enumLabels = buildEnumLabels(catalogInput);
  for (const column of catalogInput.columns) {
    const entry = codecs.get(`${column.table_name}\0${column.column_name}`);
    if (!entry || !SUPPORTED_CODECS.has(entry.codec)) throw fail("unsupported_codec");
    if (entry.sourceType !== column.postgres_type) throw fail("codec_source_type_mismatch");
    const converterType = codecConverterType(column, entry.codec);
    if (converterType === null) throw fail("unsupported_type");
    if (entry.codec === "enum-text-check") {
      const labels = enumLabels.get(column.type_name);
      if (!labels || labels.size === 0) throw fail("missing_enum_labels");
    }
  }
  const descriptors = columns.map((column) => {
    const entry = codecs.get(`${tableName}\0${column.column_name}`);
    if (!entry || !SUPPORTED_CODECS.has(entry.codec)) throw fail("unsupported_codec");
    const converterType = codecConverterType(column, entry.codec);
    if (converterType === null) throw fail("unsupported_type");
    if (entry.sourceType !== column.postgres_type) throw fail("codec_source_type_mismatch");
    if (entry.codec === "enum-text-check") {
      const labels = enumLabels.get(column.type_name);
      if (!labels || labels.size === 0) throw fail("missing_enum_labels");
    }
    return {
      column,
      codec: entry.codec,
      converterType,
      labels: entry.codec === "enum-text-check" ? enumLabels.get(column.type_name) : null,
    };
  });

  return {
    schemaVersion: ROW_ENVELOPE_VERSION,
    table: tableName,
    schema: schemaName,
    columns: descriptors,
    enumLabels,
    sql: buildSelectSql(tableName, columns, schemaName),
  };
}

export function buildRowPlan(catalogInput, tableName, options = {}) {
  const plan = createPlan(catalogInput, tableName, options);
  return publicPlan(plan);
}

function publicPlan(plan) {
  return {
    schemaVersion: plan.schemaVersion,
    table: plan.table,
    schema: plan.schema,
    columns: plan.columns.map(({ column, codec, converterType }) => ({
      name: column.column_name,
      sourceType: column.postgres_type,
      codec,
      converterType,
    })),
    arrayColumns: plan.columns.filter(({ column }) => ARRAY_TYPES.has(column.postgres_type)).map(({ column }) => column.column_name),
    sql: plan.sql,
  };
}

function validateArrayMetadata(column, value, converted, metadata) {
  if (!isPlainObject(metadata)) throw fail("invalid_array_metadata");
  assertExactKeys(metadata, EXACT_ARRAY_METADATA_KEYS, "invalid_array_metadata");
  if (typeof metadata.isNull !== "boolean") throw fail("invalid_array_metadata");
  if (value === null) {
    if (metadata.isNull !== true || metadata.ndims !== null || metadata.lowerBound !== null) throw fail("array_null_metadata_mismatch");
    return;
  }
  if (metadata.isNull !== false || !Number.isInteger(metadata.ndims) || ![0, 1].includes(metadata.ndims)) throw fail("array_shape_unsupported");
  const parsed = JSON.parse(converted);
  const empty = parsed.length === 0;
  if (empty) {
    if (metadata.ndims !== 0 || metadata.lowerBound !== null) throw fail("array_shape_mismatch");
  } else if (metadata.ndims !== 1 || metadata.lowerBound !== 1) {
    throw fail("array_shape_unsupported");
  }
}

function validateSequenceUuidArray(column, converted) {
  if (column.column_name !== "normalized_emoji_ids" || !SEQUENCE_UUID_ARRAY_TABLES.has(column.table_name)) return;
  let ids;
  try {
    ids = JSON.parse(converted);
  } catch {
    throw fail("invalid_sequence_uuid_array");
  }
  if (!Array.isArray(ids) || ids.length === 0 || ids.some((id) => typeof id !== "string" || !UUID_TEXT_RE.test(id))) {
    throw fail("invalid_sequence_uuid_array");
  }
}

function convertDescriptor(descriptor, rawValue, metadata) {
  const { column, codec, converterType } = descriptor;
  if (rawValue !== null && typeof rawValue !== "string") throw fail("invalid_source_value");
  if (rawValue === null && column.not_null) throw fail("null_forbidden");
  if (codec === "enum-text-check" && rawValue !== null) {
    const labels = descriptor.labels;
    if (!labels?.has(rawValue)) throw fail("invalid_enum_label");
  }
  let converted;
  try {
    converted = convertPgText(converterType, rawValue);
  } catch (error) {
    throw fail("invalid_column_value", error);
  }
  if (ARRAY_TYPES.has(column.postgres_type)) {
    validateArrayMetadata(column, rawValue, converted, metadata);
    validateSequenceUuidArray(column, converted);
  }
  return converted;
}

function convertEnvelopeWithPlan(plan, envelope) {
  assertExactKeys(envelope, EXACT_ENVELOPE_KEYS, "invalid_row_envelope");
  if (envelope.schemaVersion !== ROW_ENVELOPE_VERSION || envelope.table !== plan.table) throw fail("row_envelope_identity_mismatch");
  if (!Array.isArray(envelope.columns)) throw fail("invalid_row_columns");
  const expectedColumns = plan.columns.map(({ column }) => column.column_name);
  if (envelope.columns.length !== expectedColumns.length || envelope.columns.some((name, index) => name !== expectedColumns[index])) throw fail("row_column_order_mismatch");
  assertExactKeys(envelope.values, expectedColumns, "row_values_columns_mismatch");
  const arrayColumns = plan.columns.filter(({ column }) => ARRAY_TYPES.has(column.postgres_type)).map(({ column }) => column.column_name);
  assertExactKeys(envelope.arrayMetadata, arrayColumns, "row_array_metadata_columns_mismatch");

  const bindings = plan.columns.map((descriptor) => convertDescriptor(
    descriptor,
    envelope.values[descriptor.column.column_name],
    envelope.arrayMetadata[descriptor.column.column_name],
  ));
  return {
    schemaVersion: ROW_ENVELOPE_VERSION,
    table: plan.table,
    columns: expectedColumns,
    bindings,
  };
}

/**
 * Compile catalog and table validation once, then reuse the returned closure
 * for every envelope from that table. The closure has a read-only `.plan`
 * snapshot for callers that also need the generated source projection.
 */
export function compileRowConverter(catalogInput, tableName, options = {}) {
  const plan = createPlan(catalogInput, tableName, options);
  const convert = (envelope) => convertEnvelopeWithPlan(plan, envelope);
  Object.defineProperty(convert, "plan", { value: publicPlan(plan), enumerable: true });
  return convert;
}

export function convertRowEnvelope(catalogInput, tableName, envelope, options = {}) {
  return compileRowConverter(catalogInput, tableName, options)(envelope);
}

async function writeAtomic(filePath, content) {
  const absolute = path.resolve(filePath);
  await fs.mkdir(path.dirname(absolute), { recursive: true });
  const temporary = `${absolute}.tmp-${process.pid}-${randomBytes(6).toString("hex")}`;
  try {
    await fs.writeFile(temporary, content, { encoding: "utf8", mode: 0o600, flag: "wx" });
    await fs.chmod(temporary, 0o600);
    await fs.rename(temporary, absolute);
  } catch (error) {
    await fs.rm(temporary, { force: true }).catch(() => {});
    throw error;
  }
}

export const USAGE = `Usage: row-conversion.mjs --catalog PATH --table TABLE --sql-out PATH [--schema NAME] [--credential-descriptor PATH]

Generates a catalog-driven PostgreSQL exact-text row projection. It never
connects to PostgreSQL, reads rows, or applies D1 SQL.
Credential-bearing catalogs require the explicit, value-free transform descriptor.
`;

async function main() {
  const args = process.argv.slice(2);
  if (args.includes("--help") || args.includes("-h")) {
    console.log(USAGE);
    return;
  }
  const values = {};
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    const equals = arg.indexOf("=");
    const name = equals >= 0 ? arg.slice(0, equals) : arg;
    const value = equals >= 0 ? arg.slice(equals + 1) : args[++index];
    if (name === "--catalog") values.catalog = value;
    else if (name === "--table") values.table = value;
    else if (name === "--schema") values.schema = value;
    else if (name === "--sql-out") values.sqlOut = value;
    else if (name === "--credential-descriptor") values.credentialDescriptorPath = value;
    else throw fail("invalid_arguments");
  }
  if (!values.catalog || !values.table || !values.sqlOut) throw fail("missing_argument");
  const catalogPath = path.resolve(values.catalog);
  const sqlPath = path.resolve(values.sqlOut);
  const descriptorPath = values.credentialDescriptorPath ? path.resolve(values.credentialDescriptorPath) : null;
  if (new Set([catalogPath, sqlPath, ...(descriptorPath ? [descriptorPath] : [])]).size !== 2 + (descriptorPath ? 1 : 0)) throw fail("output_paths_must_differ");
  let catalog;
  try {
    catalog = JSON.parse(await fs.readFile(catalogPath, "utf8"));
  } catch (error) {
    throw fail("invalid_catalog_file", error);
  }
  let credentialDescriptor;
  if (descriptorPath) {
    try {
      credentialDescriptor = JSON.parse(await fs.readFile(descriptorPath, "utf8"));
    } catch (error) {
      throw fail("credential_descriptor_file_invalid", error);
    }
  }
  const plan = buildRowPlan(catalog, values.table, {
    schema: values.schema,
    ...(credentialDescriptor === undefined ? {} : { credentialDescriptor }),
  });
  await writeAtomic(sqlPath, `${plan.sql}`);
  console.log(`Row projection generated for ${plan.table} (${plan.columns.length} columns).`);
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  main().catch((error) => {
    const code = error instanceof RowConversionError ? error.code : "row_conversion_failed";
    console.error(`Row conversion failed (${code}).`);
    process.exitCode = 1;
  });
}
