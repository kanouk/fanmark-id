#!/usr/bin/env node

/**
 * Render the plan-bound, non-user business-D1 extensions from a private
 * read-only Supabase catalog. This command never reads application rows and
 * never applies SQL. Review the generated migration files before deployment.
 */

import { promises as fs } from "node:fs";
import path from "node:path";
import process from "node:process";
import { pathToFileURL } from "node:url";

import { compileCredentialDescriptor } from "./credential-descriptor.mjs";
import { generateCredentialTransformSchema } from "./credential-transform-schema.mjs";
import { generateLifecycleGenerationSchema } from "./lifecycle-generation-schema.mjs";
import { generateLifecycleTargetSchema } from "./lifecycle-target-schema.mjs";
import { convertSchema } from "./schema-convert.mjs";
import { generateVerifiedAccessSchema } from "./verified-access-schema.mjs";

const MIGRATIONS_DIRECTORY = path.resolve("workers/api/migrations-business");
const OUTPUTS = Object.freeze([
  { file: "0001_lifecycle_target_staging.sql", key: "lifecycle" },
  { file: "0002_lifecycle_generation_staging.sql", key: "generation" },
  { file: "0003_credential_transform_staging.sql", key: "credential" },
  { file: "0004_verified_access_staging.sql", key: "verifiedAccess" },
]);

function fail(code) {
  const error = new Error(code);
  error.code = code;
  throw error;
}

function assertPrivateFileMode(filePath, stat) {
  if (process.platform !== "win32" && (stat.mode & 0o077) !== 0) {
    fail("private_catalog_file_permissions");
  }
  const resolved = path.resolve(filePath);
  if (resolved === process.cwd() || resolved.startsWith(`${process.cwd()}${path.sep}`)) {
    fail("private_catalog_must_be_outside_repository");
  }
}

async function readPrivateJson(envName) {
  const filePath = process.env[envName];
  if (typeof filePath !== "string" || filePath.length === 0) fail(`${envName.toLowerCase()}_required`);
  const stat = await fs.stat(filePath).catch(() => null);
  if (!stat?.isFile()) fail("private_catalog_file_missing");
  assertPrivateFileMode(filePath, stat);
  let value;
  try {
    value = JSON.parse(await fs.readFile(filePath, "utf8"));
  } catch {
    fail("private_catalog_json_invalid");
  }
  return value;
}

function renderMigration({ file, plan, sourceFingerprint, statements, seedStatements = [] }) {
  if (!Array.isArray(statements) || statements.length === 0 ||
      statements.some((statement) => typeof statement !== "string" || statement.includes("\0") ||
        !/^(?:CREATE|ALTER)\s+(?:TABLE|INDEX|TRIGGER)\b/iu.test(statement.trim()))) {
    fail("business_extension_statement_invalid");
  }
  const approvedSeeds = seedStatements.map((statement) => statement.replace(/;\s*$/u, ""));
  if (file === "0004_verified_access_staging.sql") {
    const expectedSeed = 'INSERT INTO "fanmark_access_rate_policy" ("id", "window_ms", "max_attempts", "reservation_ms") VALUES (1, 300000, 5, 30000) ON CONFLICT("id") DO NOTHING';
    if (approvedSeeds.length !== 1 || approvedSeeds[0] !== expectedSeed) fail("business_extension_seed_unexpected");
  } else if (approvedSeeds.length !== 0) {
    fail("business_extension_seed_unexpected");
  }

  const lines = [
    "-- STAGING ONLY: plan-bound business D1 runtime extension.",
    "-- Generated by scripts/migration/business-schema-extensions.mjs.",
    "-- DDL applies no Supabase or user rows; the final migration seeds one target runtime policy row.",
    `-- Source fingerprint: ${sourceFingerprint}`,
    `-- Extension digest: ${plan.extensionDigest}`,
    "",
    ...statements.map((statement) => {
      const normalized = statement.trim();
      return /;\s*$/u.test(normalized) ? normalized : `${normalized};`;
    }),
    ...approvedSeeds.map((statement) => `${statement};`),
    "",
  ];
  return lines.join("\n");
}

export function buildBusinessSchemaExtensionMigrations({ catalog, descriptor } = {}) {
  if (!catalog || !descriptor) fail("business_extension_inputs_required");
  compileCredentialDescriptor({ catalog, descriptor });
  const convertedSchema = convertSchema(catalog, { credentialDescriptor: descriptor });
  const lifecycle = generateLifecycleTargetSchema({ catalog, convertedSchema, credentialDescriptor: descriptor });
  const generation = generateLifecycleGenerationSchema({ catalog, convertedSchema, lifecyclePlan: lifecycle, credentialDescriptor: descriptor });
  const credential = generateCredentialTransformSchema({ catalog, convertedSchema, lifecyclePlan: lifecycle, generationPlan: generation, descriptor });
  const verifiedAccess = generateVerifiedAccessSchema({ catalog, convertedSchema, lifecyclePlan: lifecycle, generationPlan: generation, credentialPlan: credential });
  const plans = { lifecycle, generation, credential, verifiedAccess };
  const migrations = OUTPUTS.map(({ file, key }) => {
    const plan = plans[key];
    return {
      file,
      content: renderMigration({
        file,
        plan,
        sourceFingerprint: lifecycle.sourceFingerprint,
        statements: plan.statements,
        seedStatements: plan.seedStatements ?? [],
      }),
      extensionDigest: plan.extensionDigest,
      statementCount: plan.statements.length + (plan.seedStatements?.length ?? 0),
    };
  });
  return {
    sourceFingerprint: lifecycle.sourceFingerprint,
    sourceCounts: convertedSchema.report.source,
    deployable: convertedSchema.report.deployable,
    unresolvedGateCount: convertedSchema.report.unresolvedGateCount,
    migrations,
  };
}

async function main(args) {
  const mode = args[0];
  if (args.length !== 1 || !["--write", "--check"].includes(mode)) {
    fail("usage: business-schema-extensions.mjs --write|--check");
  }
  const catalog = await readPrivateJson("FANMARK_PRIVATE_SCHEMA_READINESS_CATALOG");
  const descriptor = await readPrivateJson("FANMARK_PRIVATE_CREDENTIAL_DESCRIPTOR");
  const result = buildBusinessSchemaExtensionMigrations({ catalog, descriptor });
  const summaries = [];
  for (const migration of result.migrations) {
    const target = path.join(MIGRATIONS_DIRECTORY, migration.file);
    if (mode === "--write") {
      await fs.writeFile(target, migration.content, { mode: 0o644 });
      summaries.push({ file: migration.file, status: "written", bytes: Buffer.byteLength(migration.content), extensionDigest: migration.extensionDigest });
      continue;
    }
    const existing = await fs.readFile(target, "utf8").catch(() => null);
    if (existing !== migration.content) fail("business_extension_migration_drift");
    summaries.push({ file: migration.file, status: "matches", bytes: Buffer.byteLength(existing), extensionDigest: migration.extensionDigest });
  }
  process.stdout.write(`${JSON.stringify({
    sourceFingerprint: result.sourceFingerprint,
    sourceCounts: result.sourceCounts,
    deployable: result.deployable,
    unresolvedGateCount: result.unresolvedGateCount,
    migrations: summaries,
  }, null, 2)}\n`);
}

const invokedPath = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : "";
if (invokedPath === import.meta.url) {
  main(process.argv.slice(2)).catch((error) => {
    process.stderr.write(`${error?.code ?? "business_extension_failed"}\n`);
    process.exitCode = 1;
  });
}
