#!/usr/bin/env node

/**
 * Generate the additive D1 migration that repairs the fixed-width timestamps
 * in the lifecycle-generation triggers from the already-applied 0002 file.
 * The source catalog is schema-only; this tool never reads application rows
 * or applies SQL.
 */

import { promises as fs } from "node:fs";
import path from "node:path";
import process from "node:process";
import { pathToFileURL } from "node:url";

import { sha256Hex } from "./snapshot-format.mjs";
import { convertSchema } from "./schema-convert.mjs";
import { generateLifecycleTargetSchema } from "./lifecycle-target-schema.mjs";
import {
  buildLifecycleGenerationTimestampRepairStatements,
  generateLifecycleGenerationSchema,
} from "./lifecycle-generation-schema.mjs";

const MIGRATION_FILE = "0017_lifecycle_generation_timestamp_precision.sql";
const MIGRATIONS_DIRECTORY = path.resolve("workers/api/migrations-business");
const CANONICAL_TIMESTAMP = "strftime('%Y-%m-%dT%H:%M:%f000Z', 'now')";

function fail(code) {
  const error = new Error(code);
  error.code = code;
  throw error;
}

function migrationContent({ generation, statements }) {
  const replacements = generation.objectInventory.triggers.filter((trigger) =>
    trigger.sql.includes(CANONICAL_TIMESTAMP),
  );
  if (replacements.length !== 22 || statements.length !== replacements.length * 2) {
    fail("lifecycle_generation_timestamp_repair_unexpected_count");
  }
  const digest = sha256Hex({
    migration: MIGRATION_FILE,
    schemaVersion: generation.schemaVersion,
    replacements: replacements.map(({ name, sql }) => ({ name, sql })),
  });
  const lines = [
    "-- STAGING ONLY: forward repair for lifecycle-generation trigger timestamps.",
    "-- Generated by scripts/migration/lifecycle-generation-timestamp-repair.mjs.",
    "-- Replaces 22 trigger definitions from applied migration 0002; no application rows are read or written.",
    `-- Canonical trigger digest: ${digest}`,
    "",
    ...statements.map((statement) => {
      const normalized = statement.trim();
      return /;\s*$/u.test(normalized) ? normalized : normalized + ";";
    }),
    "",
  ];
  return { content: lines.join("\n"), digest, triggerCount: replacements.length };
}

export function buildLifecycleGenerationTimestampRepairMigration(catalog) {
  if (!catalog || typeof catalog !== "object" || Array.isArray(catalog)) {
    fail("invalid_schema_catalog");
  }
  const convertedSchema = convertSchema(catalog);
  const lifecyclePlan = generateLifecycleTargetSchema({ catalog, convertedSchema });
  const generation = generateLifecycleGenerationSchema({ catalog, convertedSchema, lifecyclePlan });
  const statements = buildLifecycleGenerationTimestampRepairStatements(generation);
  return migrationContent({ generation, statements });
}

async function readPrivateCatalog() {
  const filePath = process.env.FANMARK_PRIVATE_SCHEMA_READINESS_CATALOG;
  if (typeof filePath !== "string" || filePath.length === 0) {
    fail("fanmark_private_schema_readiness_catalog_required");
  }
  const stat = await fs.stat(filePath).catch(() => null);
  if (!stat?.isFile()) fail("private_schema_catalog_missing");
  if (process.platform !== "win32" && (stat.mode & 0o077) !== 0) {
    fail("private_schema_catalog_permissions");
  }
  const [catalogPath, repoPath] = await Promise.all([
    fs.realpath(filePath),
    fs.realpath(process.cwd()),
  ]);
  if (catalogPath === repoPath || catalogPath.startsWith(`${repoPath}${path.sep}`)) {
    fail("private_schema_catalog_must_be_outside_repository");
  }
  try {
    return JSON.parse(await fs.readFile(catalogPath, "utf8"));
  } catch {
    fail("private_schema_catalog_invalid");
  }
}

async function run(mode) {
  if (mode !== "--write" && mode !== "--check") {
    fail("usage: lifecycle-generation-timestamp-repair.mjs --write|--check");
  }
  const catalog = await readPrivateCatalog();
  const generated = buildLifecycleGenerationTimestampRepairMigration(catalog);
  const target = path.join(MIGRATIONS_DIRECTORY, MIGRATION_FILE);
  const existing = await fs.readFile(target, "utf8").catch(() => null);
  let status;
  if (mode === "--check") {
    if (existing !== generated.content) fail("lifecycle_generation_timestamp_migration_drift");
    status = "matches";
  } else if (existing === null) {
    await fs.writeFile(target, generated.content, { encoding: "utf8", mode: 0o644, flag: "wx" });
    status = "written";
  } else if (existing === generated.content) {
    status = "matches";
  } else {
    fail("lifecycle_generation_timestamp_migration_is_immutable");
  }
  process.stdout.write(JSON.stringify({
    file: path.relative(process.cwd(), target),
    status,
    triggerCount: generated.triggerCount,
    digest: generated.digest,
  }, null, 2) + "\n");
}

const invokedPath = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : "";
if (invokedPath === import.meta.url) {
  run(process.argv[2]).catch((error) => {
    process.stderr.write((error?.code ?? "lifecycle_generation_timestamp_repair_failed") + "\n");
    process.exitCode = 1;
  });
}
